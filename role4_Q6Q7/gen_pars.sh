#!/usr/bin/env bash
# Generate the Role-4 parameter files from the validated wICE baseline
# (reference/smoke_wice_baseline96.par). Only these lines are changed:
#   base_filename, time_max, dtsave(1:2), time_stepper, flux_scheme, limiter
# Everything else (grid, BCs, CFL, physics) is copied verbatim, so the runs
# can differ ONLY in the numerical scheme.
set -euo pipefail
cd "$(dirname "$0")"
REF=reference/smoke_wice_baseline96.par
TMAX=${TMAX:-5.d0}      # final time
DTLOG=${DTLOG:-0.05d0}  # log interval   (dtsave(1))
DTDAT=${DTDAT:-0.25d0}  # snapshot interval (dtsave(2))

#        name        stepper    flux   limiter
RUNS="   baseline96  threestep  tvdlf  minmod
         woodward96  threestep  tvdlf  woodward
         vanleer96   threestep  tvdlf  vanleer
         koren96     threestep  tvdlf  koren
         cada3_96    threestep  tvdlf  cada3
         hll96       threestep  hll    minmod
         hllc96      threestep  hllc   minmod
         roe_tvd96   onestep    tvd    minmod"

mkdir -p pars
while read -r name stepper flux lim; do
  [ -z "$name" ] && continue
  sed -e "s|^ base_filename=.*| base_filename='output/${name}'|" \
      -e "s|^ time_max=.*| time_max=${TMAX}|" \
      -e "s|^ dtsave(1)=.*| dtsave(1)=${DTLOG}|" \
      -e "s|^ dtsave(2)=.*| dtsave(2)=${DTDAT}|" \
      -e "s|^ time_stepper=.*| time_stepper='${stepper}'|" \
      -e "s|^ flux_scheme=.*| flux_scheme=20*'${flux}'|" \
      -e "s|^ limiter=.*| limiter=20*'${lim}'|" \
      -e "1s|.*|! Role 4 (Q6/Q7): ${name} = ${stepper} + ${flux} + ${lim}. Generated by gen_pars.sh from ${REF}|" \
      "$REF" > "pars/${name}.par"
done <<< "$RUNS"
sed -i "1a ! OPTIONAL Q7 run: AMRVAC forces onestep AND dimsplit=T for 'tvd', and the HD Roe\n! eigen-system has no explicit tracer wave -> not a one-variable comparison." pars/roe_tvd96.par

echo "Generated: $(ls pars | tr '\n' ' ')"
echo "--- Validation: baseline96.par vs the run that worked on wICE (only time/output lines may differ):"
diff "$REF" pars/baseline96.par || true
